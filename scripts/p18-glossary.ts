interface TranslateResult {
  fa: string | null;
  unmatched: string[];
}

/** نرمال‌سازی نام برای تطبیق: حروف کوچک، خط تیره به فاصله، حذف نقطه */
function normalizeForTranslate(name: string): string {
  return name
    .toLowerCase()
    .replace(/[’'`]/g, "")
    .replace(/[-–—]/g, " ")
    .replace(/[()]/g, " ")
    .replace(/[,\/;.]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * ترجمه نام حرکت — تطبیق بلندترین عبارت شناخته‌شده از چپ به راست.
 * خروجی null یعنی «ترجمه موجود نیست» (صادقانه) — هرگز نام ساختگی نمی‌سازد.
 */
export function translateExerciseName(enName: string): TranslateResult {
  const normalized = normalizeForTranslate(enName);
  const override = PHRASE_OVERRIDES[normalized];
  if (override) return { fa: override, unmatched: [] };

  const words = normalized.split(" ");
  const segments: { fa: string; role: Role }[] = [];
  const unmatched: string[] = [];
  let i = 0;

  // تطبیق حریصانه از بلندترین n-gram (تا ۴ توکن) به کوتاه‌ترین (۱ توکن)
  while (i < words.length) {
    let matched = false;
    for (let n = Math.min(4, words.length - i); n >= 1; n--) {
      const phrase = words.slice(i, i + n).join(" ");
      const def = TOKEN_MAP[phrase];
      if (def) {
        if (def.fa !== "") segments.push({ fa: def.fa, role: def.role });
        i += n;
        matched = true;
        break;
      }
    }
    if (!matched) {
      unmatched.push(words[i]);
      i += 1;
    }
  }

  if (unmatched.length > 0) return { fa: null, unmatched };

  // ترتیب فارسی: حرکت + تجهیزات + موقعیت/صفت‌ها (به ترتیب ظاهر در نام)
  const movement = segments.filter((s) => s.role === "movement").map((s) => s.fa);
  const equipment = segments.filter((s) => s.role === "equipment").map((s) => s.fa);
  const rest = segments
    .filter((s) => s.role !== "movement" && s.role !== "equipment")
    .map((s) => s.fa);

  // حذف تکرارهای پشت‌سرهم (مثلاً «دستگاه دستگاه»)
  const dedup = (arr: string[]) =>
    arr.filter((v, idx) => idx === 0 || v !== arr[idx - 1]);

  // حذف حروف ربط سرگردان در ابتدا/انتها («از روی از» → تمیز) — حروف ربط
  // میانی حفظ می‌شوند چون معنادارند («پرس با کش مقاومتی»)
  const GLUE = new Set(["از", "به", "و", "رو", "در", "با", "روی", "زیر", "یا", "از روی", "رو به"]);

  const parts = [...dedup(movement), ...dedup(equipment), ...dedup(rest)]
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
  while (parts.length > 0 && GLUE.has(parts[parts.length - 1])) parts.pop();
  while (parts.length > 0 && GLUE.has(parts[0])) parts.shift();

  const fa = parts.join(" ").trim();
  return { fa: fa.length > 0 ? fa : null, unmatched };
}
